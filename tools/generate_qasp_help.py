#!/usr/bin/env python3
"""Embed the editable help copy in C++; no JSON reader or network at runtime.

Run from any directory. --check fails if the committed generated file is stale.
Copyright notices and the NASA NOSA 1.3 licence in ../LICENSE apply.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/help/qasp-help.json'
OUTPUT = ROOT / 'src/gui_and_draw/QaspHelpData.inc'
DIAGRAMS = {
    'forces': 'Forces', 'thrust': 'Thrust', 'angle': 'Angle', 'drag': 'Drag',
    'wing': 'Wing', 'taper': 'Taper', 'sweep': 'Sweep', 'dihedral': 'Dihedral',
    'airfoil': 'Airfoil', 'cg': 'Cg', 'units': 'Units', 'axes': 'Axes',
    'body': 'Body', 'tail': 'Tail', 'measure': 'Measure', 'results': 'Results',
    'altitude': 'Altitude', 'mesh': 'Mesh', 'workflow': 'Workflow',
}
PARM_FIELDS = ('group', 'name', 'descript', 'title', 'meaning', 'effect', 'example', 'units')
LESSON_FIELDS = ('id', 'category', 'title', 'summary', 'diagram', 'meaning', 'effect',
                 'example', 'try_it', 'caution', 'keywords')


def quoted(text):
    # Content is deliberately ASCII to behave the same on MSVC and FLTK builds.
    return json.dumps(text, ensure_ascii=True)


def generate(data):
    assert data['schema_version'] == 1, 'Unknown help schema'
    seen = set()
    for entry in data['tooltips']:
        assert set(entry) == set(PARM_FIELDS), 'Invalid tooltip fields'
        assert all(isinstance(entry[f], str) for f in PARM_FIELDS)
        assert all(entry[f].strip() for f in ('group', 'name', 'title', 'meaning', 'effect', 'example'))
        key = tuple(entry[f] for f in ('group', 'name', 'descript'))
        assert key not in seen, f'Duplicate tooltip key: {key}'
        seen.add(key)
        assert entry['group'] != '*', 'Do not guess context from a parameter name alone'
        assert sum(len(entry[f].split()) for f in ('meaning', 'effect', 'example', 'units')) <= 115, key
    seen = set()
    for lesson in data['lessons']:
        assert set(lesson) == set(LESSON_FIELDS), 'Invalid lesson fields'
        assert all(isinstance(lesson[f], str) and lesson[f].strip() for f in LESSON_FIELDS)
        assert lesson['id'] not in seen, 'Duplicate lesson id'
        seen.add(lesson['id'])
        assert lesson['diagram'] in DIAGRAMS, 'Unknown lesson diagram'
        words = sum(len(lesson[f].split()) for f in ('meaning', 'effect', 'example', 'try_it', 'caution'))
        assert words <= 190, f'Lesson is no longer short: {lesson["id"]} ({words} words)'
    lines = [
        '// Generated by tools/generate_qasp_help.py from src/help/qasp-help.json.',
        '// Edit the JSON, not this file. NASA NOSA 1.3; see LICENSE.',
        '', 'static const QaspHelp::ParmHelp g_ParmHelp[] =', '{',
    ]
    for entry in data['tooltips']:
        lines += ['    { ' + ', '.join(quoted(entry[f]) for f in PARM_FIELDS) + ' },']
    lines += ['};', '', 'static const QaspHelp::Lesson g_Lessons[] =', '{']
    for entry in data['lessons']:
        values = [('QaspHelp::Diagram::' + DIAGRAMS[entry[f]]) if f == 'diagram'
                  else quoted(entry[f]) for f in LESSON_FIELDS]
        lines += ['    { ' + ', '.join(values) + ' },']
    lines += ['};', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        data = json.loads(SOURCE.read_text())
        result = generate(data)
    except (AssertionError, KeyError, ValueError) as exc:
        print(f'Invalid help content: {exc}', file=sys.stderr)
        return 1
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            print('Generated help is stale. Run tools/generate_qasp_help.py', file=sys.stderr)
            return 1
    else:
        OUTPUT.write_text(result)
    print(f'Help content OK: {len(data["tooltips"])} parameter explanations, {len(data["lessons"])} short lessons')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
